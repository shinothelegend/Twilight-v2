#!/usr/bin/env node
/**
 * Generates lib/generated/contracts.ts from deployments/arbitrumSepolia.json.
 *
 * The JSON is the single source of truth (written by the Foundry deploy script via
 * contracts/script/sync-deployment.mjs). This step only re-emits it as `as const` TypeScript so
 * wagmi/viem can infer function names, argument types and return types at compile time.
 *
 * Runs automatically on `npm run dev` and `npm run build`.
 */
import {readFileSync, writeFileSync, mkdirSync} from "node:fs";
import {dirname, resolve} from "node:path";
import {fileURLToPath} from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const deployment = JSON.parse(
  readFileSync(resolve(root, "deployments", "arbitrumSepolia.json"), "utf8"),
);

const banner = `// AUTO-GENERATED by scripts/generate-contracts.mjs — do not edit.
// Source of truth: deployments/arbitrumSepolia.json (written by the Foundry deploy script).
`;

const body = `
export const deployment = {
  chainId: ${deployment.chainId},
  network: ${JSON.stringify(deployment.network)},
  explorer: ${JSON.stringify(deployment.explorer)},
  deployer: ${JSON.stringify(deployment.deployer)},
  startBlock: ${deployment.startBlock}n,
  deployedAt: ${deployment.deployedAt},
} as const;

export const twilightTokenAddress = ${JSON.stringify(
  deployment.contracts.TwilightToken.address,
)} as const;

export const twilightStakingAddress = ${JSON.stringify(
  deployment.contracts.TwilightStaking.address,
)} as const;

export const twilightTokenAbi = ${JSON.stringify(
  deployment.contracts.TwilightToken.abi,
  null,
  2,
)} as const;

export const twilightStakingAbi = ${JSON.stringify(
  deployment.contracts.TwilightStaking.abi,
  null,
  2,
)} as const;
`;

const target = resolve(root, "lib", "generated", "contracts.ts");
mkdirSync(dirname(target), {recursive: true});
writeFileSync(target, banner + body);
console.log(`Generated ${target}`);
